"use client";

// Strategic plans live in the browser (localStorage) for the prototype.
// One plan = one wellbeing-services county. A real deployment would keep them in the county's own database.
import { useSyncExternalStore } from "react";
import { counties, getCounty, national } from "@/lib/data";

export type InvestmentKind = "one-off" | "yearly";
export type InvestmentStatus = "planned" | "ordered" | "paid";

export type Investment = {
  id: string;
  name: string;
  kind: InvestmentKind;
  /** our estimate, € */
  estimate: number;
  /** what it really cost, entered after the supplier quote / invoice, € */
  actual?: number;
  supplier?: string;
  status: InvestmentStatus;
  /** generated by the planner (kept in sync with the inputs until someone edits it) */
  auto?: "ct-time" | "training" | "protocol" | "scanner";
  note?: string;
};

/** Weekly aggregate for the public health-centre door only. No patient rows, no occupational or private route. */
export type WeekReport = {
  id: string;
  weekStart: string;
  pathwaysStarted: number;
  /** Median days, public health-centre visit to CT report. */
  medianDaysVisitToCt: number | null;
  ctScansUsed: number;
  otherCtMedianWait: number | null;
  source: "mock" | "manual" | "county";
};

export type PlanInputs = {
  slug: string;
  /** chest-CT slots a week the county wants to reserve for the GP route */
  scansPerWeek: number;
  start: string; // YYYY-MM
  horizonYears: number;
  /** € a year the county can put into the programme */
  yearlyFunding: number;
  /** € available once (equipment, setup) */
  oneOffBudget: number;
  /** CT slots a week the county's existing scanners can spare */
  spareCtSlots: number;
  /** new CT scanners the county is buying anyway or for this plan */
  newScanners: number;
  /** radiologist hours a week that can go to this route */
  radiologistHours: number;
  /** family doctors joining next year (growth already budgeted elsewhere) */
  newGps: number;
};

export type Plan = {
  id: string;
  name: string;
  createdAt: string;
  status: "draft" | "active";
  example?: boolean;
  inputs: PlanInputs;
  costs: { ctEuro: number; scannerEuro: number; slotsPerScanner: number };
  investments: Investment[];
  weeks: WeekReport[];
};

const KEY = "liwe.plans.v6";
const PREVIOUS_KEYS = ["liwe.plans.v5", "liwe.plans.v4"];
/** Same chest-CT stop as the plan verdict. A starting plan should sit on the safe side of it. */
const CAPACITY_SHARE = 0.05;
const listeners = new Set<() => void>();
let cacheRaw: string | null | undefined;
let cache: Plan[] = [];
const EMPTY: Plan[] = [];

export const uid = () => Math.random().toString(36).slice(2, 10);

function read(): Plan[] {
  let raw: string | null = null;
  try {
    raw = localStorage.getItem(KEY);
  } catch {
    raw = null;
  }
  if (raw === cacheRaw) return cache;
  cacheRaw = raw;
  try {
    cache = raw ? (JSON.parse(raw) as Plan[]) : plansFromPrevious();
  } catch {
    cache = seed();
  }
  if (!raw) write(cache);
  return cache;
}

/** Saved plans were sized to cancer counts, which put every county over the 5% stop. Pull them back to the stop. */
function plansFromPrevious(): Plan[] {
  let old: string | null = null;
  try {
    for (const key of PREVIOUS_KEYS) {
      old = localStorage.getItem(key);
      if (old) break;
    }
  } catch {
    old = null;
  }
  if (!old) return seed();
  try {
    return (JSON.parse(old) as Plan[]).map((p) => {
      const cap = scansInsideCapacity(p.inputs.slug);
      if (p.inputs.scansPerWeek <= cap) return p;
      return { ...p, inputs: { ...p.inputs, scansPerWeek: cap } };
    });
  } catch {
    return seed();
  }
}

function write(plans: Plan[]) {
  const raw = JSON.stringify(plans);
  try {
    localStorage.setItem(KEY, raw);
  } catch {
    /* private mode: keep in memory */
  }
  cacheRaw = raw;
  cache = plans;
  listeners.forEach((l) => l());
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  const onStorage = (e: StorageEvent) => e.key === KEY && cb();
  window.addEventListener("storage", onStorage);
  return () => {
    listeners.delete(cb);
    window.removeEventListener("storage", onStorage);
  };
}

export function usePlans(): Plan[] {
  return useSyncExternalStore(subscribe, read, () => EMPTY);
}

/** false during server render / hydration, true once the browser store is read */
export function useHydrated() {
  return useSyncExternalStore(
    () => () => {},
    () => true,
    () => false,
  );
}

export function savePlan(plan: Plan) {
  const plans = read();
  const i = plans.findIndex((p) => p.id === plan.id);
  write(i < 0 ? [plan, ...plans] : plans.map((p) => (p.id === plan.id ? plan : p)));
}

export function deletePlan(id: string) {
  write(read().filter((p) => p.id !== id));
}

export function resetExamples() {
  write(seed());
}

// ---------- defaults ----------
export const DEFAULT_COSTS = {
  ctEuro: 165, // middle of €132–198, Tyks price list 2022
  scannerEuro: 450_000, // ESTIMATE for a new 64-slice CT incl. installation — replace with the supplier's quote
  slotsPerScanner: 100, // ESTIMATE: chest-CT slots a week one extra scanner frees up
};

const fiPopulation = () => counties.reduce((a, c) => a + c.population, 0);

/** Most scans a week that stay at or under 5% of the county's estimated chest CT. */
export function scansInsideCapacity(slug: string) {
  const c = getCounty(slug);
  const week = (national.thoraxCt2024 / 52) * (c.population / fiPopulation());
  const max = week * CAPACITY_SHARE;
  const halfStep = Math.floor(max * 2) / 2;
  if (halfStep >= 0.5) return halfStep;
  return Math.max(0.1, Math.floor(max * 10) / 10);
}

/** Start inside the 5% stop. The cancer-count figure is usually already past it. */
export function suggestedScans(slug: string) {
  const c = getCounty(slug);
  const clinical = Math.max(1, Math.round((c.casesPerYearEst * 0.5 * national.pathwaysPerConfirmedCancer) / 52));
  return Math.min(clinical, scansInsideCapacity(slug));
}

export function defaultInputs(slug: string): PlanInputs {
  return {
    slug,
    scansPerWeek: suggestedScans(slug),
    start: "2026-01",
    horizonYears: 1,
    yearlyFunding: 150_000,
    oneOffBudget: 50_000,
    spareCtSlots: 8,
    newScanners: 0,
    radiologistHours: 4,
    newGps: 0,
  };
}

function seed(): Plan[] {
  const mk = (slug: string, name: string, over: Partial<PlanInputs>): Plan => ({
    id: `ex-${slug}`,
    name,
    createdAt: "2025-12-01",
    status: "active",
    example: true,
    inputs: { ...defaultInputs(slug), ...over },
    costs: { ...DEFAULT_COSTS },
    investments: [],
    weeks: [],
  });
  return [
    mk("kainuu", "Kainuu · direct CT pilot", { start: "2026-01", yearlyFunding: 60_000, radiologistHours: 2, spareCtSlots: 5 }),
    mk("city-of-helsinki", "Helsinki · fast lung track", {
      start: "2026-03",
      yearlyFunding: 250_000,
      spareCtSlots: 10,
      radiologistHours: 6,
      newGps: 40,
    }),
  ];
}
