"""Turn Statistics Finland county boundaries into compact SVG paths for the canvas.

Projects lon/lat to a flat grid scaled for Finland's latitude, drops tiny islands,
and simplifies rings with Douglas-Peucker until the whole path set fits in a few
kilobytes. Output is a TypeScript fragment written to scripts/out/map_paths.ts.
"""
import json
import math
import os

# Finnish feature name -> the English name used in our county dataset.
NAME_MAP = {
    "Itä-Uudenmaan hyvinvointialue": "East Uusimaa",
    "Keski-Uudenmaan hyvinvointialue": "Central Uusimaa",
    "Länsi-Uudenmaan hyvinvointialue": "West Uusimaa",
    "Vantaan ja Keravan hyvinvointialue": "Vantaa and Kerava",
    "Varsinais-Suomen hyvinvointialue": "Southwest Finland",
    "Satakunnan hyvinvointialue": "Satakunta",
    "Kanta-Hämeen hyvinvointialue": "Kanta-Häme",
    "Pirkanmaan hyvinvointialue": "Pirkanmaa",
    "Päijät-Hämeen hyvinvointialue": "Päijät-Häme",
    "Kymenlaakson hyvinvointialue": "Kymenlaakso",
    "Etelä-Karjalan hyvinvointialue": "South Karelia",
    "Etelä-Savon hyvinvointialue": "South Savo",
    "Pohjois-Savon hyvinvointialue": "North Savo",
    "Pohjois-Karjalan hyvinvointialue": "North Karelia",
    "Keski-Suomen hyvinvointialue": "Central Finland",
    "Etelä-Pohjanmaan hyvinvointialue": "South Ostrobothnia",
    "Pohjanmaan hyvinvointialue": "Ostrobothnia",
    "Keski-Pohjanmaan hyvinvointialue": "Central Ostrobothnia",
    "Pohjois-Pohjanmaan hyvinvointialue": "North Ostrobothnia",
    "Kainuun hyvinvointialue": "Kainuu",
    "Lapin hyvinvointialue": "Lapland",
    "Helsingin kaupunki": "City of Helsinki",
    "Ahvenanmaa": "Åland",
}

LAT0 = 65.0
KX = math.cos(math.radians(LAT0))


def project(lon, lat):
    return lon * KX, -lat


def ring_area(pts):
    a = 0.0
    for i in range(len(pts)):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % len(pts)]
        a += x1 * y2 - x2 * y1
    return abs(a) / 2


def perp(p, a, b):
    (px, py), (ax, ay), (bx, by) = p, a, b
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def simplify(pts, eps):
    if len(pts) < 4:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        worst, idx = 0.0, -1
        for k in range(i + 1, j):
            d = perp(pts[k], pts[i], pts[j])
            if d > worst:
                worst, idx = d, k
        if worst > eps and idx > 0:
            keep[idx] = True
            stack.append((i, idx))
            stack.append((idx, j))
    return [p for p, k in zip(pts, keep) if k]


def build(eps, island_frac):
    with open("raw/hva.geojson", encoding="utf-8") as f:
        gj = json.load(f)

    xs, ys, out = [], [], []
    for feat in gj["features"]:
        fi_name = feat["properties"]["nimi"]
        name = NAME_MAP.get(fi_name)
        if name is None:
            raise SystemExit(f"unmapped county: {fi_name}")

        geom = feat["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]

        rings = []
        for poly in polys:
            outer = [project(x, y) for x, y, *_ in poly[0]]
            rings.append(outer)
        biggest = max(ring_area(r) for r in rings)
        rings = [r for r in rings if ring_area(r) >= biggest * island_frac]

        simplified = [simplify(r, eps) for r in rings]
        simplified = [r for r in simplified if len(r) >= 3]
        out.append((name, simplified))
        for r in simplified:
            for x, y in r:
                xs.append(x)
                ys.append(y)

    minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)
    span = max(maxx - minx, maxy - miny)
    W = 1000.0
    ox = (W - (maxx - minx) / span * W) / 2
    oy = (W - (maxy - miny) / span * W) / 2

    def tx(x, y):
        return ((x - minx) / span * W + ox, (y - miny) / span * W + oy)

    paths = []
    for name, rings in out:
        d = []
        for r in rings:
            pts = [tx(x, y) for x, y in r]
            d.append("M" + "L".join(f"{px:.1f} {py:.1f}" for px, py in pts) + "Z")
        paths.append((name, "".join(d)))
    return paths


for eps, frac in ((0.010, 0.04), (0.016, 0.05), (0.024, 0.06), (0.034, 0.08)):
    paths = build(eps, frac)
    total = sum(len(d) for _, d in paths)
    print(f"eps={eps:<6} island_frac={frac:<5} total path chars = {total:,}")

EPS, FRAC = 0.024, 0.06
paths = build(EPS, FRAC)
os.makedirs("scripts/out", exist_ok=True)
with open("scripts/out/map_paths.ts", "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_map.py from Statistics Finland WFS\n")
    f.write(f"// layer tilastointialueet:hyvinvointialue4500k_2025, Douglas-Peucker eps={EPS}\n")
    f.write("export const COUNTY_PATHS: Record<string, string> = {\n")
    for name, d in paths:
        f.write(f'  {json.dumps(name, ensure_ascii=False)}: "{d}",\n')
    f.write("};\n")

print(f"\nwrote scripts/out/map_paths.ts  ({os.path.getsize('scripts/out/map_paths.ts'):,} bytes)")
print(f"counties: {len(paths)}")
